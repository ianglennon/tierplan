# Probe packages the lint and gate sections copy fixtures into; removed on exit.
sleep_probe_dir="internal/zzforbidigoprobe"
vite_pid=""
stop_vite() {
  if [ -n "${vite_pid}" ]; then
    kill "${vite_pid}" 2>/dev/null
    wait "${vite_pid}" 2>/dev/null
    vite_pid=""
  fi
}
trap 'stop_vite; rm -rf "${scratch}" "${ui_probe}" "${sleep_probe_dir}"' EXIT

# expect <fail|pass> <name> <command...>
expect() {
  local want="$1" name="$2"
  shift 2
  local out rc
  out="$("$@" 2>&1)"
  rc=$?
  if [ "$want" = "fail" ] && [ "$rc" -eq 0 ]; then
    echo "SCRIPT TEST FAIL: ${name} (expected non-zero, got 0)"
    failures=$((failures + 1))
  elif [ "$want" = "pass" ] && [ "$rc" -ne 0 ]; then
    echo "SCRIPT TEST FAIL: ${name} (expected 0, got ${rc})"
    echo "${out}" | sed 's/^/    /'
    failures=$((failures + 1))
  fi
  LAST_OUT="$out"
}

# expect_out <name> <fixed-string>: the last command's output must contain it.
expect_out() {
  if ! grep -qF -- "$2" <<<"${LAST_OUT}"; then
    echo "SCRIPT TEST FAIL: $1 (output missing: $2)"
    failures=$((failures + 1))
  fi
}

