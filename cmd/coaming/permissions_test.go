const generatedHeader = "Code generated by coaming permissions; DO NOT EDIT."

// runPermissions runs `coaming permissions` with args and returns its stdout.
func runPermissions(t *testing.T, args ...string) (string, error) {
	t.Helper()
	cmd := newPermissionsCmd()
	var out, errOut bytes.Buffer
	cmd.SetOut(&out)
	cmd.SetErr(&errOut)
	cmd.SetArgs(args)
	err := cmd.Execute()
	return out.String(), err
}

func TestPermissionsMarkdownListsEveryPermissionAndTheRulesThatCombineThem(t *testing.T) {
	out, err := runPermissions(t, "--format", "markdown")
	if err != nil {
		t.Fatal(err)
	}
	first := strings.SplitN(out, "\n", 5)
	if !strings.Contains(strings.Join(first[:3], "\n"), generatedHeader) {
		t.Fatalf("the first lines are %q, want the generated header", first[:3])
	}
	if !strings.Contains(out, "| Permission | Scope | Viewer | Operator | Admin | Instance admin | Dangerous | Description |") {
		t.Fatalf("no matrix header row in:\n%s", out)
	}
	for _, want := range []string{
		"`containers.read`", "`containers.exec`", "`environments.configure`", "`users.manage`", "`backup.manage`",
		"union", "Operator", "instance admin", "Delegation",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("markdown lacks %q", want)
		}
	}
	// One table row per registered permission: header, separator and the rows.
	rows := 0
	for _, line := range strings.Split(out, "\n") {
		if strings.HasPrefix(line, "| `") {
			rows++
		}
	}
	if want := len(rbac.All()); rows != want {
		t.Errorf("%d permission rows, want %d (one per registered permission)", rows, want)
	}
}

func TestPermissionsTypeScriptHasTheArraysAndTheRequirementRecord(t *testing.T) {
	out, err := runPermissions(t, "--format", "typescript")
	if err != nil {
		t.Fatal(err)
	}
	if head := strings.Join(strings.SplitN(out, "\n", 5)[:3], "\n"); !strings.Contains(head, generatedHeader) {
		t.Fatalf("the first lines are %q, want the generated header", head)
	}
	for _, want := range []string{
		"export const GLOBAL_PERMISSIONS", "export const ENVIRONMENT_PERMISSIONS", "export const EXTRA_PERMISSIONS",
		"export const DANGEROUS_PERMISSIONS", "export const PERMISSION_REQUIREMENTS",
		`"users.manage": { kind: "instance" }`,
		`"containers.exec": { kind: "extra", role: "operator" }`,
		`"environments.read": { kind: "role", role: "viewer" }`,
	} {
		if !strings.Contains(out, want) {
			t.Errorf("typescript lacks %q", want)
		}
	}
}

func TestPermissionsOutputIsIdenticalBetweenRuns(t *testing.T) {
	for _, format := range []string{"markdown", "typescript"} {
		a, err := runPermissions(t, "--format", format)
		if err != nil {
			t.Fatal(err)
		}
		b, err := runPermissions(t, "--format", format)
		if err != nil {
			t.Fatal(err)
		}
		if a != b {
			t.Errorf("%s output differs between two runs", format)
		}
	}
}

func TestPermissionsDefaultsToMarkdown(t *testing.T) {
	def, err := runPermissions(t)
	if err != nil {
		t.Fatal(err)
	}
	md, _ := runPermissions(t, "--format", "markdown")
	if def != md {
		t.Fatal("the default format is not markdown")
	}
}

func TestPermissionsRefusesAnUnknownFormatAndNamesTheAllowedOnes(t *testing.T) {
	_, err := runPermissions(t, "--format", "yaml")
	if err == nil {
		t.Fatal("an unknown format was accepted")
	}
	if !strings.Contains(err.Error(), "markdown") || !strings.Contains(err.Error(), "typescript") {
		t.Fatalf("error %q does not name the allowed values", err)
	}
}

// The committed files are what the generator prints, so a registry change
// without `make gen` fails here as well as in `make gen-check`.
func TestTheCommittedPermissionFilesMatchTheGenerator(t *testing.T) {
	for format, path := range map[string]string{
		"markdown":   "../../docs/permissions.md",
		"typescript": "../../web/src/api/permissions.gen.ts",
	} {
		want, err := os.ReadFile(path) //nolint:gosec // a fixed repository path
		if err != nil {
			t.Fatalf("read %s: %v (run make gen)", path, err)
		}
		got, err := runPermissions(t, "--format", format)
		if err != nil {
			t.Fatal(err)
		}
		if got != string(want) {
			t.Errorf("%s is out of date: run make gen", path)
		}
	}
}
